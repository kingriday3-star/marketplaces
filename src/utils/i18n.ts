const RTL_LANG_PREFIXES = ['ar', 'ur', 'fa', 'he', 'ps'];

export function isRtlLanguage(lang: SupportedLanguage = 'bn'): boolean {
  const base = (lang || 'bn').split('-')[0].toLowerCase();
  return RTL_LANG_PREFIXES.includes(base);
}

export function resolveBaseLang(lang: SupportedLanguage = 'bn'): string {
  if (!lang) return 'bn';
  const lower = lang.toLowerCase();
  if (lower in TRANSLATIONS) return lower;
  const base = lower.split('-')[0];
  if (base in TRANSLATIONS) return base;
  return 'en';
}


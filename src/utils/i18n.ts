export function getProductTitle(
  product: { id?: string; title: string; titleEn?: string; updatedAt?: string },
  lang: SupportedLanguage = 'bn'
): string {
  const baseLang = resolveBaseLang(lang);
  if (product.updatedAt) {
    return product.title;
  }
  if (baseLang === 'bn') {
    return product.title;
  }
  if (product.id) {
    const dict = PRODUCT_MULTILANG[product.id]?.titles;
    if (dict?.[lang]) return dict[lang]!;
    if (dict?.[baseLang]) return dict[baseLang]!;
  }
  return product.titleEn || product.title;
}

